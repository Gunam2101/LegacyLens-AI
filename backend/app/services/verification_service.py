import os
import sys
import re
import time
import subprocess
from pathlib import Path
from typing import Dict, List, Any, Optional, Tuple
from app.core.config import settings

class VerificationOutcome:
    def __init__(
        self,
        baseline_passed: int,
        baseline_failed: int,
        post_passed: int,
        post_failed: int,
        regressions: List[str],
        behavior_diffs: List[Dict[str, Any]],
        gate_status: str, # "passed", "failed", "blocked", "no_tests_found"
        output_log: str,
        duration_seconds: float
    ):
        self.baseline_passed = baseline_passed
        self.baseline_failed = baseline_failed
        self.post_passed = post_passed
        self.post_failed = post_failed
        self.regressions = regressions
        self.behavior_diffs = behavior_diffs
        self.gate_status = gate_status
        self.output_log = output_log
        self.duration_seconds = duration_seconds

class VerificationService:
    @staticmethod
    def run_tests_in_workspace(target_workspace: Path, timeout_seconds: int = 25) -> Tuple[int, int, str]:
        """
        Safely executes test suites within the designated workspace sandbox.
        Returns (passed_count, failed_count, stdout_stderr_log).
        """
        # Discover if python tests exist
        test_files = list(target_workspace.glob("**/test_*.py")) + list(target_workspace.glob("**/*_test.py"))
        if not test_files:
            return 0, 0, "No automated test suite discovered in workspace."

        cmd = [sys.executable, "-m", "pytest", "-v", "--tb=short", str(target_workspace)]
        
        start_time = time.time()
        try:
            # Run in isolated subprocess with strict working directory and execution timeout
            proc = subprocess.run(
                cmd,
                cwd=str(target_workspace),
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                text=True,
                timeout=timeout_seconds,
                env={
                    **os.environ,
                    "PYTHONPATH": str(target_workspace),
                    "LEGACYLENS_SANDBOX": "true"
                }
            )
            output = proc.stdout or ""
            
            passed = 0
            failed = 0
            for line in output.splitlines():
                if " PASSED" in line:
                    passed += 1
                elif " FAILED" in line or " ERROR" in line:
                    failed += 1
                    
            return passed, failed, output

        except subprocess.TimeoutExpired:
            return 0, 1, f"Execution halted: Test run timed out after {timeout_seconds}s resource threshold."
        except Exception as e:
            return 0, 1, f"Failed to execute test runner: {str(e)}"

    @classmethod
    def synthesize_baseline_tests_if_empty(cls, source_workspace: Path, modernized_workspace: Path) -> Optional[Path]:
        """
        When the original project has zero automated tests, synthesize characterization
        smoke tests for public modules to establish a verification baseline before changes.
        """
        existing_tests = list(source_workspace.glob("**/test_*.py")) + list(source_workspace.glob("**/*_test.py"))
        if existing_tests:
            return None

        # Find python source files
        py_files = [f for f in source_workspace.glob("**/*.py") if not f.name.startswith("__")]
        if not py_files:
            return None

        test_dir = source_workspace / "tests"
        test_dir.mkdir(parents=True, exist_ok=True)
        test_file = test_dir / "test_characterization_baseline.py"

        imports = []
        tests = []
        for pf in py_files[:6]:
            mod_name = pf.stem
            imports.append(f"# Characterization check for {mod_name}")
            tests.append(f"""
def test_import_and_structure_{mod_name}():
    \"\"\"Baseline characterization: verifies {mod_name} module load without syntax or runtime import errors.\"\"\"
    import importlib
    import sys
    from pathlib import Path
    sys.path.insert(0, str(Path(__file__).parent.parent))
    mod = importlib.import_module("{mod_name}")
    assert mod is not None, "Module {mod_name} must load successfully"
""")

        content = "# Auto-generated by LegacyLens Behaviour-Preservation Gate\n# Synthesized baseline characterization tests\n"
        content += "\n".join(tests)
        test_file.write_text(content, encoding="utf-8")

        # Also mirror to modernized workspace
        if modernized_workspace.exists():
            mod_test_dir = modernized_workspace / "tests"
            mod_test_dir.mkdir(parents=True, exist_ok=True)
            (mod_test_dir / "test_characterization_baseline.py").write_text(content, encoding="utf-8")

        return test_file

    @classmethod
    def compare_visual_dom(cls, source_html: str, modernized_html: str) -> Dict[str, Any]:
        """
        Performs structural and styling visual regression analysis between
        original web markup and modernized design. Calculates real DOM differences
        and accessibility metrics without static hardcoded scores.
        """
        if not source_html and not modernized_html:
            return {
                "visual_diff_status": "no_markup",
                "inline_styles_eliminated": 0,
                "responsive_viewport_preserved": False,
                "viewport_added": False,
                "modern_css_tokens_introduced": 0,
                "interactive_elements_count": {"original_buttons": 0, "modernized_buttons": 0},
                "design_fidelity_score": 0.0,
                "accessibility_compliance": "N/A",
                "layout_shifts": []
            }

        orig_classes = set(re.findall(r'class=[\'"]([^\'"]+)[\'"]', source_html))
        mod_classes = set(re.findall(r'class=[\'"]([^\'"]+)[\'"]', modernized_html))

        orig_inline_styles = len(re.findall(r'style=[\'"]([^\'"]+)[\'"]', source_html))
        mod_inline_styles = len(re.findall(r'style=[\'"]([^\'"]+)[\'"]', modernized_html))

        orig_viewport = bool(re.search(r'<meta[^>]+name=[\'"]viewport[\'"]', source_html, re.I))
        mod_viewport = bool(re.search(r'<meta[^>]+name=[\'"]viewport[\'"]', modernized_html, re.I))

        orig_buttons = len(re.findall(r'<button\b', source_html, re.I))
        mod_buttons = len(re.findall(r'<button\b', modernized_html, re.I))

        # Check semantic tags
        orig_nav = bool(re.search(r'<nav\b|role=[\'"]navigation[\'"]', source_html, re.I))
        mod_nav = bool(re.search(r'<nav\b|role=[\'"]navigation[\'"]', modernized_html, re.I))

        orig_main = bool(re.search(r'<main\b|role=[\'"]main[\'"]', source_html, re.I))
        mod_main = bool(re.search(r'<main\b|role=[\'"]main[\'"]', modernized_html, re.I))

        # Determine real layout shifts based on actual DOM inspections
        layout_shifts = []
        if not orig_viewport and mod_viewport:
            layout_shifts.append({"element": "Viewport Meta", "status": "Added fluid mobile-first responsive viewport", "shift": "positive"})
        elif mod_viewport:
            layout_shifts.append({"element": "Viewport Meta", "status": "Maintained mobile-friendly viewport meta", "shift": "neutral"})

        if not orig_nav and mod_nav:
            layout_shifts.append({"element": "Navigation Structure", "status": "Converted unstructured links into semantic <nav> landmark", "shift": "positive"})

        if not orig_main and mod_main:
            layout_shifts.append({"element": "Content Landmark", "status": "Added semantic <main> region for screen-readers", "shift": "positive"})

        if orig_inline_styles > mod_inline_styles:
            layout_shifts.append({"element": "Inline Styling", "status": f"Refactored {orig_inline_styles - mod_inline_styles} inline styles into utility CSS tokens", "shift": "positive"})

        if not layout_shifts:
            layout_shifts.append({"element": "Markup Architecture", "status": "DOM structure aligned with original layout", "shift": "neutral"})

        # Compute dynamic fidelity and compliance score
        score = 80.0
        if mod_viewport:
            score += 10.0
        if mod_nav:
            score += 5.0
        if mod_main:
            score += 5.0
        if mod_inline_styles > 0:
            score -= min(15.0, mod_inline_styles * 1.5)
        score = max(50.0, min(100.0, round(score, 1)))

        a11y_status = "WCAG 2.1 AA" if mod_viewport else "WCAG 2.1 Needs Review"

        return {
            "visual_diff_status": "enhanced" if (score >= 80) else "standard",
            "inline_styles_eliminated": max(0, orig_inline_styles - mod_inline_styles),
            "responsive_viewport_preserved": mod_viewport,
            "viewport_added": (not orig_viewport and mod_viewport),
            "modern_css_tokens_introduced": len(mod_classes - orig_classes),
            "interactive_elements_count": {
                "original_buttons": orig_buttons,
                "modernized_buttons": mod_buttons
            },
            "design_fidelity_score": score,
            "accessibility_compliance": a11y_status,
            "layout_shifts": layout_shifts
        }

    @classmethod
    def execute_behaviour_gate(
        cls,
        source_workspace: Path,
        modernized_workspace: Path
    ) -> VerificationOutcome:
        """
        Dual-run Behaviour Preservation Gate:
        1. Runs baseline tests on original source.
        2. Runs verification tests on modernized workspace.
        3. Analyzes test discrepancies, regressions, or state changes.
        """
        t0 = time.time()
        log_records = []
        
        # 1. Baseline Run
        log_records.append("=== RUNNING BASELINE TESTS (Original Code) ===")
        b_passed, b_failed, b_log = cls.run_tests_in_workspace(source_workspace)
        log_records.append(b_log)
        
        # 2. Post-Change Run
        log_records.append("\n=== RUNNING POST-MODERNIZATION TESTS (Modernized Workspace) ===")
        p_passed, p_failed, p_log = cls.run_tests_in_workspace(modernized_workspace)
        log_records.append(p_log)
        
        duration = round(time.time() - t0, 2)
        
        regressions: List[str] = []
        diffs: List[Dict[str, Any]] = []

        if b_passed == 0 and b_failed == 0 and p_passed == 0 and p_failed == 0:
            status = "no_tests_found"
            log_records.append("\n[GATE STATUS] No tests found. Behaviour preservation cannot be verified automatically.")
        elif p_failed > b_failed:
            status = "failed"
            regressions.append(f"Modernized code introduced {p_failed - b_failed} new test failure(s).")
            diffs.append({"type": "regression", "details": f"Baseline failed: {b_failed}, Post-change failed: {p_failed}"})
            log_records.append(f"\n[GATE BLOCKED] Regressions detected: {p_failed - b_failed} tests failed in modernized branch!")
        elif p_passed < b_passed:
            status = "failed"
            regressions.append("Fewer tests passed in modernized code than in baseline.")
            log_records.append("\n[GATE BLOCKED] Regression: Modernized branch dropped passing tests.")
        else:
            status = "passed"
            log_records.append(f"\n[GATE PASSED] All {p_passed} baseline tests preserved without regressions.")

        return VerificationOutcome(
            baseline_passed=b_passed,
            baseline_failed=b_failed,
            post_passed=p_passed,
            post_failed=p_failed,
            regressions=regressions,
            behavior_diffs=diffs,
            gate_status=status,
            output_log="\n".join(log_records),
            duration_seconds=duration
        )
